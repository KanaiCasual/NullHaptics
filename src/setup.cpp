static fs::path LocalAppData()
{
	wchar_t *val = nullptr;
	size_t len = 0;
	_wdupenv_s( &val, &len, L"LOCALAPPDATA" );
	fs::path p = val ? fs::path( val ) : fs::path();
	free( val );
	return p;
}

static fs::path InstallDir()
{
	return LocalAppData() / kDriverLeaf;
}

static bool ExtractResource( int id, const fs::path &dest )
{
	HMODULE mod = GetModuleHandleW( nullptr );
	HRSRC res = FindResourceW( mod, MAKEINTRESOURCEW( id ), reinterpret_cast<LPCWSTR>( RT_RCDATA ) );
	if ( !res )
		return false;
	HGLOBAL global = LoadResource( mod, res );
	const void *data = global ? LockResource( global ) : nullptr;
	DWORD size = SizeofResource( mod, res );
	if ( !data )
		return false;

	std::error_code ec;
	fs::create_directories( dest.parent_path(), ec );
	std::ofstream f( dest, std::ios::binary | std::ios::trunc );
	if ( !f )
		return false;
	f.write( static_cast<const char *>( data ), size );
	return f.good();
}

static std::string ReadTextFile( const fs::path &p )
{
	std::ifstream f( p, std::ios::binary );
	std::stringstream ss;
	ss << f.rdbuf();
	return ss.str();
}

// Minimal extraction of a JSON string array by key, good enough for openvrpaths.vrpath
// (written by vrpathreg itself, so the shape is stable).
static std::vector<std::wstring> ParseJsonStringArray( const std::string &json, const std::string &key )
{
	std::vector<std::wstring> result;
	size_t k = json.find( "\"" + key + "\"" );
	if ( k == std::string::npos )
		return result;
	size_t colon = json.find( ':', k );
	if ( colon == std::string::npos )
		return result;
	size_t open = json.find_first_not_of( " \t\r\n", colon + 1 );
	if ( open == std::string::npos || json[open] != '[' )  // key may be null, not an array
		return result;
	size_t close = json.find( ']', open );
	if ( close == std::string::npos )
		return result;

	size_t pos = open;
	while ( true )
	{
		size_t qs = json.find( '"', pos );
		if ( qs == std::string::npos || qs > close )
			break;
		std::string s;
		size_t i = qs + 1;
		while ( i < close && json[i] != '"' )
		{
			if ( json[i] == '\\' && i + 1 < close )
			{
				s += json[i + 1];
				i += 2;
			}
			else
			{
				s += json[i];
				++i;
			}
		}
		int wlen = MultiByteToWideChar( CP_UTF8, 0, s.c_str(), -1, nullptr, 0 );
		std::wstring ws( wlen > 0 ? wlen - 1 : 0, L'\0' );
		if ( wlen > 0 )
			MultiByteToWideChar( CP_UTF8, 0, s.c_str(), -1, ws.data(), wlen );
		result.push_back( ws );
		pos = i + 1;
	}
	return result;
}

static fs::path OpenVRPathsFile()
{
	fs::path lad = LocalAppData();
	return lad.empty() ? fs::path() : lad / L"openvr" / L"openvrpaths.vrpath";
}

static fs::path FindVrPathReg()
{
	fs::path vrpaths = OpenVRPathsFile();
	if ( !vrpaths.empty() && fs::exists( vrpaths ) )
	{
		for ( const auto &runtime : ParseJsonStringArray( ReadTextFile( vrpaths ), "runtime" ) )
		{
			fs::path candidate = fs::path( runtime ) / L"bin" / L"win64" / L"vrpathreg.exe";
			if ( fs::exists( candidate ) )
				return candidate;
		}
	}
	fs::path fallback = L"C:\\Program Files (x86)\\Steam\\steamapps\\common\\SteamVR\\bin\\win64\\vrpathreg.exe";
	if ( fs::exists( fallback ) )
		return fallback;
	return {};
}

static std::vector<std::wstring> RegisteredExternalDrivers()
{
	fs::path vrpaths = OpenVRPathsFile();
	if ( vrpaths.empty() || !fs::exists( vrpaths ) )
		return {};
	return ParseJsonStringArray( ReadTextFile( vrpaths ), "external_drivers" );
}

static int RunVrPathReg( const fs::path &vrpathreg, const std::wstring &verb, const fs::path &driverPath )
{
	std::wstring cmd = L"\"" + vrpathreg.wstring() + L"\" " + verb;
	if ( !driverPath.empty() )
		cmd += L" \"" + driverPath.wstring() + L"\"";

	STARTUPINFOW si{};
	si.cb = sizeof( si );
	PROCESS_INFORMATION pi{};
	std::wstring mutableCmd = cmd;
	// CREATE_NO_WINDOW: vrpathreg is a console app; without this a console flashes up.
	if ( !CreateProcessW( nullptr, mutableCmd.data(), nullptr, nullptr, FALSE, CREATE_NO_WINDOW, nullptr, nullptr, &si, &pi ) )
		return -1;
	WaitForSingleObject( pi.hProcess, INFINITE );
	DWORD code = 1;
	GetExitCodeProcess( pi.hProcess, &code );
	CloseHandle( pi.hProcess );
	CloseHandle( pi.hThread );
	return static_cast<int>( code );
}

static bool IsProcessRunning( const wchar_t *name )
{
	HANDLE snap = CreateToolhelp32Snapshot( TH32CS_SNAPPROCESS, 0 );
	if ( snap == INVALID_HANDLE_VALUE )
		return false;
	PROCESSENTRY32W pe{};
	pe.dwSize = sizeof( pe );
	bool found = false;
	if ( Process32FirstW( snap, &pe ) )
	{
		do
		{
			if ( _wcsicmp( pe.szExeFile, name ) == 0 )
			{
				found = true;
				break;
			}
		} while ( Process32NextW( snap, &pe ) );
	}
	CloseHandle( snap );
	return found;
}

static bool SamePath( const std::wstring &a, const std::wstring &b )
{
	std::error_code ec;
	fs::path pa = fs::weakly_canonical( a, ec );
	fs::path pb = fs::weakly_canonical( b, ec );
	return _wcsicmp( pa.c_str(), pb.c_str() ) == 0;
}

static bool IsInstalled( const fs::path &driverPath )
{
	for ( const auto &d : RegisteredExternalDrivers() )
		if ( SamePath( d, driverPath.wstring() ) )
			return true;
	return false;
}

// Unregister every registration whose leaf folder is the current driver name (any
// case, e.g. an earlier lowercase "nullhaptics") or the legacy name, and delete the
// leftover folders. Path comparisons are case-insensitive on Windows, so the current
// and prior-case installs collapse to the same name here.
static void RemoveNullHapticsRegistrations( const fs::path &vrpathreg, const fs::path &driverPath, std::wstring &log )
{
	for ( const auto &d : RegisteredExternalDrivers() )
	{
		std::wstring leaf = fs::path( d ).filename().wstring();
		if ( _wcsicmp( leaf.c_str(), kDriverLeaf ) == 0 || _wcsicmp( leaf.c_str(), kLegacyLeaf ) == 0 )
		{
			if ( !SamePath( d, driverPath.wstring() ) )
				log += L"Removed old registration: " + d + L"\r\n";
			RunVrPathReg( vrpathreg, L"removedriver", fs::path( d ) );
		}
	}
	RunVrPathReg( vrpathreg, L"removedriver", driverPath );

	std::error_code ec;
	fs::path legacy = LocalAppData() / kLegacyLeaf;
	if ( fs::exists( legacy ) )
		fs::remove_all( legacy, ec );
}

static bool DoInstall( const fs::path &vrpathreg, const fs::path &driverPath, std::wstring &log )
{
	log += L"Installing to " + driverPath.wstring() + L" ...\r\n";

	// Wipe any existing folder first so it is recreated with this exact casing —
	// Windows keeps the original on-disk case, and SteamVR shows the folder name.
	std::error_code wipeEc;
	fs::remove_all( driverPath, wipeEc );

	bool ok = ExtractResource( IDR_DRIVER_MANIFEST, driverPath / L"driver.vrdrivermanifest" )
		&& ExtractResource( IDR_DRIVER_VRSETTINGS, driverPath / L"resources" / L"settings" / L"default.vrsettings" )
		&& ExtractResource( IDR_DRIVER_DLL, driverPath / L"bin" / L"win64" / L"driver_NullHaptics.dll" );
	if ( !ok )
	{
		log += L"ERROR: could not extract the driver files.\r\n";
		if ( IsProcessRunning( L"vrserver.exe" ) )
			log += L"SteamVR is running and may have the driver DLL locked - close SteamVR and retry.\r\n";
		return false;
	}

	RemoveNullHapticsRegistrations( vrpathreg, driverPath, log );
	RunVrPathReg( vrpathreg, L"adddriver", driverPath );
	if ( IsInstalled( driverPath ) )
	{
		log += L"Installed. All SteamVR haptics will be silenced.\r\n";
		if ( IsProcessRunning( L"vrserver.exe" ) )
			log += L"SteamVR is running - restart it for the change to take effect.\r\n";
		return true;
	}
	log += L"ERROR: registration did not stick (vrpathreg adddriver failed).\r\n";
	return false;
}

static bool DoUninstall( const fs::path &vrpathreg, const fs::path &driverPath, std::wstring &log )
{
	log += L"Uninstalling...\r\n";
	RemoveNullHapticsRegistrations( vrpathreg, driverPath, log );
	if ( IsInstalled( driverPath ) )
	{
		log += L"ERROR: driver is still registered.\r\n";
		return false;
	}
	log += L"Unregistered. Haptics will work normally again.\r\n";
	if ( fs::exists( driverPath / L"driver.vrdrivermanifest" ) )
	{
		std::error_code ec;
		fs::remove_all( driverPath, ec );
		log += ec ? L"NOTE: could not delete " + driverPath.wstring() + L" (close SteamVR, delete manually).\r\n"
				  : L"Removed extracted files.\r\n";
	}
	if ( IsProcessRunning( L"vrserver.exe" ) )
		log += L"SteamVR is running - restart it for the change to take effect.\r\n";
	return true;
}

