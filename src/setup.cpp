// NullHaptics setup — self-contained installer for the NullHaptics SteamVR driver.
//
// The driver package (DLL, manifest, vrsettings) is embedded as RCDATA resources in
// this executable. Install extracts it to %LOCALAPPDATA%\NullHaptics and registers
// that path through SteamVR's own vrpathreg.exe, located via
// %LOCALAPPDATA%\openvr\openvrpaths.vrpath.
//
// Also supports silent command-line use: NullHaptics-setup.exe install | uninstall | status

